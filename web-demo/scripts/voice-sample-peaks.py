"""Precompute waveform peaks for the /languages sample calls.

Decodes every public/media/samples/*-switch.m4a and writes
src/lib/voiceSamplePeaks.ts: {slug: [N ints 0-100]}, one per bar, the
RMS of that slice of the file scaled to the loudest slice. Re-run after
replacing a sample. Needs numpy and ffmpeg (set FFMPEG to override).

    FFMPEG=/path/to/ffmpeg python3 scripts/voice-sample-peaks.py
"""
import glob, json, os, subprocess
import numpy as np

N = 140
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
FFMPEG = os.environ.get("FFMPEG", "ffmpeg")
out = {}
for path in sorted(glob.glob(os.path.join(ROOT, "public/media/samples/*-switch.m4a"))):
    slug = os.path.basename(path)[: -len("-switch.m4a")]
    raw = subprocess.run([FFMPEG, "-loglevel", "error", "-i", path, "-f", "s16le", "-ac", "1", "-ar", "8000", "-"],
                         capture_output=True, check=True).stdout
    x = np.frombuffer(raw, dtype=np.int16).astype(np.float64) / 32768.0
    edges = np.linspace(0, len(x), N + 1).astype(int)
    rms = np.array([np.sqrt(np.mean(x[a:b] ** 2)) if b > a else 0.0 for a, b in zip(edges[:-1], edges[1:])])
    v = (rms / rms.max()) ** 0.8  # mild lift so quiet words still read as bars
    out[slug] = [int(round(n * 100)) for n in v]
with open(os.path.join(ROOT, "src/lib/voiceSamplePeaks.ts"), "w") as f:
    f.write("// Generated by scripts/voice-sample-peaks.py from public/media/samples; do not edit.\n"
            "// One value per waveform bar (0-100), the RMS of that slice scaled to the loudest.\n"
            "export const VOICE_SAMPLE_PEAKS: Record<string, number[]> = {\n"
            + "\n".join(f"  {k if k.isidentifier() else json.dumps(k)}: {json.dumps(v, separators=(',', ':'))}," for k, v in out.items()) + "\n}\n")
print({k: len(v) for k, v in out.items()})
