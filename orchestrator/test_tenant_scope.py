class _FakeResp:
    status = 200

    async def text(self):
        return "ok"

    async def __aenter__(self):
        return self

    async def __aexit__(self, *exc):
        return False

    def __await__(self):
        async def _self():
            return self
        return _self().__await__()


class _FakeHttp:
    """Stands in for aiohttp.ClientSession; records every POST."""

    def __init__(self, posts):
        self.posts = posts

    def __call__(self, *args, **kwargs):
        return self

    async def __aenter__(self):
        return self

    async def __aexit__(self, *exc):
        return False

    def post(self, url, json=None, **kwargs):
        self.posts.append((url, json))
        return _FakeResp()


def _session(account_id, agent_id):
    return session_module.Session(account_id=account_id, agent_id=agent_id, call_type="phone")


_SCHEMA = """
CREATE TABLE agents (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id INTEGER,
    name TEXT NOT NULL,
    is_platform_demo INTEGER DEFAULT 0
);
CREATE TABLE accounts (
    id INTEGER PRIMARY KEY,
    plan TEXT,
    is_platform_owner INTEGER DEFAULT 0
);
CREATE TABLE integrations (
    account_id INTEGER NOT NULL,
    key TEXT NOT NULL,
    name TEXT NOT NULL,
    category TEXT NOT NULL,
    description TEXT DEFAULT '',
    status TEXT DEFAULT 'not_connected',
    config_json TEXT DEFAULT '{}',
    last_sync TEXT,
    last_error TEXT,
    PRIMARY KEY (account_id, key)
);
"""

A_URL = "https://a.example.test/hook"
B_URL = "https://b.example.test/hook"


@unittest.skipIf(pgserver is None, "pgserver not installed")
class PostgresTenantScopeTests(unittest.IsolatedAsyncioTestCase):
    @classmethod
    def setUpClass(cls):
        cls._tmp = tempfile.TemporaryDirectory()
        cls._pg = pgserver.get_server(cls._tmp.name, cleanup_mode="stop")
        cls._env = patch.dict(os.environ, {"DATABASE_URL": cls._pg.get_uri()})
        cls._env.start()
        dbconn._pool = None

    @classmethod
    def tearDownClass(cls):
        if dbconn._pool is not None:
            dbconn._pool.close()
            dbconn._pool = None
        cls._env.stop()
        cls._pg.cleanup()
        cls._tmp.cleanup()

    def setUp(self):
        conn = dbconn.connect()
        try:
            with conn:
                conn.execute("DROP TABLE IF EXISTS agents")
                conn.execute("DROP TABLE IF EXISTS integrations")
                conn.execute("DROP TABLE IF EXISTS accounts")
                for stmt in _SCHEMA.split(";"):
                    if stmt.strip():
                        conn.execute(stmt)
                # Both on a plan with the crm feature, so delivery is on.
                conn.execute("INSERT INTO accounts (id, plan) VALUES (1, 'growth'), (2, 'growth')")
                # B's webhook goes in first, so a platform-wide
                # "any connected webhook" lookup finds B's.
                for account_id, url in ((2, B_URL), (1, A_URL)):
                    conn.execute(
                        "INSERT INTO integrations (account_id, key, name, category, status, config_json) "
                        "VALUES (?, 'webhook', 'Webhook', 'crm', 'connected', ?)",
                        (account_id, json.dumps({"url": url})),
                    )
                # Agent 1 belongs to account 2 (Vistrow's demo-style agent,
                # not flagged); agent 2 belongs to account 1.
                conn.execute("INSERT INTO agents (account_id, name) VALUES (2, 'B agent')")
                conn.execute("INSERT INTO agents (account_id, name) VALUES (1, 'A agent')")
        finally:
            conn.close()

    async def test_account_a_lead_goes_only_to_account_a_webhook(self):
        posts = []
        with patch.object(tools.aiohttp, "ClientSession", _FakeHttp(posts)):
            await tools.log_lead(_session(1, 2), name="Asha", phone="+919800000000")
        self.assertEqual([url for url, _ in posts], [A_URL])

    async def test_account_a_call_end_goes_only_to_account_a_webhook(self):
        posts = []
        with patch.object(tools.aiohttp, "ClientSession", _FakeHttp(posts)), \
                patch.object(db, "save_call", return_value=None):
            await session_module.finalize_call(_session(1, 2), "room-a")
        self.assertEqual([url for url, _ in posts], [A_URL])

    def test_no_agent_never_falls_back_to_an_unflagged_agent(self):
        self.assertIsNone(db.get_agent_config(None))

    def test_no_agent_returns_only_the_flagged_platform_demo(self):
        conn = dbconn.connect()
        try:
            with conn:
                conn.execute("UPDATE agents SET is_platform_demo = 1 WHERE id = 1")
        finally:
            conn.close()
        self.assertEqual(db.get_agent_config(None)["id"], 1)

    def test_agent_lookup_scoped_to_account(self):
        self.assertEqual(db.get_agent_config(2, account_id=1)["name"], "A agent")
        self.assertIsNone(db.get_agent_config(1, account_id=1))
        self.assertIsNone(db.get_agent_config(None, account_id=1))


class DeliverySettingsTests(unittest.IsolatedAsyncioTestCase):
    async def _deliver(self, integrations, lead):
        posts = []
        with patch.object(tools.aiohttp, "ClientSession", _FakeHttp(posts)), \
                patch.object(db, "get_delivery_integrations", return_value=integrations), \
                patch.object(db, "touch_integration_sync"), \
                patch.object(db, "mark_integration_error"), \
                patch.object(db, "set_call_arthaleads_status"), \
                patch.object(db, "record_integration_delivery"):
            await tools._deliver_to_integrations(1, lead)
        return posts

    async def test_webhook_skips_events_its_owner_did_not_choose(self):
        integ = [{"key": "webhook", "config": {"url": A_URL, "events": ["call_completed"]}}]
        self.assertEqual(await self._deliver(integ, {"type": "lead_update", "name": "Asha"}), [])
        self.assertEqual(len(await self._deliver(integ, {"type": "call_completed", "name": "Asha"})), 1)

    async def test_platform_lead_update_counts_as_lead_update(self):
        integ = [{"key": "slack", "config": {"url": A_URL, "events": ["appointment_booked"]}}]
        self.assertEqual(await self._deliver(integ, {"type": "platform_lead_update", "name": "Asha"}), [])

    async def test_whatsapp_defaults_to_call_end_only(self):
        integ = [{"key": "whatsapp", "config": {"url": A_URL}}]
        self.assertEqual(await self._deliver(integ, {"type": "lead_update", "phone": "+91"}), [])
        self.assertEqual(len(await self._deliver(integ, {"type": "call_completed", "phone": "+91"})), 1)

    async def test_webhook_leaves_out_fields_its_owner_unticked(self):
        integ = [{"key": "webhook", "config": {"url": A_URL, "fields": ["name", "phone"]}}]
        lead = {
            "type": "call_completed", "name": "Asha", "phone": "+91", "email": "a@example.test",
            "transcript": [{"role": "user", "text": "hello"}],
        }
        [(_, body)] = await self._deliver(integ, lead)
        self.assertEqual(body["name"], "Asha")
        self.assertNotIn("email", body)
        self.assertNotIn("transcript", body)

    async def test_arthaleads_ignores_field_choice(self):
        integ = [{"key": "arthaleads", "config": {"token": "t", "fields": ["name"]}}]
        lead = {"type": "call_completed", "name": "Asha", "phone": "+91", "email": "a@example.test"}
        [(_, body)] = await self._deliver(integ, lead)
        self.assertEqual(body["email"], "a@example.test")


