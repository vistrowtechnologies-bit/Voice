def set_call_arthaleads_status(call_id: int | None, status: str, error: str | None = None) -> None:
    """Records this specific call's ArthaLeads delivery outcome — separate
    from the integration-level last_sync/last_error, which only reflect the
    most recent attempt across every call. Best-effort: a status-tracking
    hiccup must never surface to the caller or disturb call teardown."""
    if call_id is None:
        return
    conn = dbconn.connect()
    try:
        with conn:
            conn.execute(
                f"UPDATE calls SET arthaleads_status = ?, arthaleads_synced_at = {_NOW}, "
                "arthaleads_error = ? WHERE id = ?",
                (status, error, call_id),
            )
    except psycopg.Error:
        pass
    finally:
        conn.close()


def set_call_recording(call_id: int | None, recording_key: str) -> None:
    """Attaches this call's R2 recording key after upload finishes — same
    save-now-update-later shape as set_call_arthaleads_status above, since
    the recording isn't ready until after save_call's initial INSERT.
    Best-effort: a failure here must never disturb call teardown."""
    if call_id is None:
        return
    conn = dbconn.connect()
    try:
        with conn:
            conn.execute(
                "UPDATE calls SET recording_key = ? WHERE id = ?",
                (recording_key, call_id),
            )
    except psycopg.Error:
        pass
    finally:
        conn.close()
