_EMAIL_OTP_TTL_SECONDS = 10 * 60
_EMAIL_OTP_RESEND_SECONDS = 60
_EMAIL_OTP_MAX_ATTEMPTS = 5


def _hash_email_code(code: str) -> str:
    # A six-digit code has too little entropy for an unkeyed database hash.
    # Pepper it with the deployment's auth secret so a database-only leak
    # cannot be brute-forced by trying all one million possible codes.
    pepper = os.environ.get("AUTH_SECRET") or "local-email-verification"
    return hashlib.sha256(f"{pepper}:{code}".encode()).hexdigest()


def create_email_verification(user_id: int) -> tuple[str | None, int]:
    """Create a six-digit inbox-verification code.

    Returns ``(code, 60)`` when sent is allowed, or ``(None, seconds_left)``
    while the per-user resend cooldown is active. Only a SHA-256 hash is
    stored and every previous code is invalidated when a new one is minted.
    """
    now = int(time.time())
    conn = _connect()
    try:
        latest = conn.execute(
            "SELECT created_epoch FROM email_verifications WHERE user_id = ? ORDER BY id DESC LIMIT 1",
            (user_id,),
        ).fetchone()
        if latest is not None:
            elapsed = now - int(latest["created_epoch"])
            if elapsed < _EMAIL_OTP_RESEND_SECONDS:
                return None, _EMAIL_OTP_RESEND_SECONDS - elapsed
        code = f"{secrets.randbelow(1_000_000):06d}"
        with conn:
            conn.execute("UPDATE email_verifications SET used = 1 WHERE user_id = ? AND used = 0", (user_id,))
            conn.execute(
                "INSERT INTO email_verifications "
                "(user_id, code_hash, expires_at, created_epoch) VALUES (?, ?, ?, ?)",
                (user_id, _hash_email_code(code), now + _EMAIL_OTP_TTL_SECONDS, now),
            )
        return code, _EMAIL_OTP_RESEND_SECONDS
    finally:
        conn.close()


def consume_email_verification(email: str, code: str) -> int | None:
    """Validate and burn the newest OTP for ``email``; return its user id."""
    conn = _connect()
    try:
        row = conn.execute(
            "SELECT ev.id, ev.user_id, ev.code_hash, ev.expires_at, ev.attempts, ev.used "
            "FROM email_verifications ev JOIN users u ON u.id = ev.user_id "
            "WHERE u.email = ? ORDER BY ev.id DESC LIMIT 1",
            (email.lower(),),
        ).fetchone()
        if (
            row is None
            or row["used"]
            or int(row["expires_at"]) < int(time.time())
            or int(row["attempts"]) >= _EMAIL_OTP_MAX_ATTEMPTS
        ):
            return None
        if not secrets.compare_digest(str(row["code_hash"]), _hash_email_code(code)):
            with conn:
                conn.execute("UPDATE email_verifications SET attempts = attempts + 1 WHERE id = ?", (row["id"],))
            return None
        with conn:
            conn.execute("UPDATE email_verifications SET used = 1 WHERE id = ?", (row["id"],))
            conn.execute(f"UPDATE users SET email_verified_at = COALESCE(email_verified_at, {_NOW}) WHERE id = ?", (row["user_id"],))
        return int(row["user_id"])
    finally:
        conn.close()


