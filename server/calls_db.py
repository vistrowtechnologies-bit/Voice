def _credits_used_in_period(conn, account_id: int, rates: dict, period_start: str | None) -> tuple[float, dict, dict]:
    """Shared by billing_summary (current period) and the overage webhook
    handler (a just-closed period) — credits burned by calls started at or
    after period_start (None = all-time, only used as a display fallback)."""
    query = (
        "SELECT COALESCE(call_type, 'browser') call_type, voice, "
        "COALESCE(SUM(duration_seconds), 0) / 60.0 m FROM calls WHERE account_id = ?"
    )
    params: list = [account_id]
    if period_start:
        query += " AND started_at >= ?"
        params.append(period_start)
    query += " GROUP BY call_type, voice"

    by_type: dict[str, float] = {}
    by_voice_tier: dict[str, float] = {}
    used = 0.0
    for row in conn.execute(query, params).fetchall():
        call_type = row["call_type"] if row["call_type"] in rates else "browser"
        tier = voice_tier(row["voice"])
        minutes = row["m"]
        credits = minutes * rates.get(call_type, 1.0) * _VOICE_TIER_MULTIPLIERS[tier]
        by_type[call_type] = round(by_type.get(call_type, 0.0) + minutes, 1)
        by_voice_tier[tier] = round(by_voice_tier.get(tier, 0.0) + minutes, 1)
        used += credits
    return round(used, 1), by_type, by_voice_tier


def billing_summary(account_id: int) -> dict:
    conn = _connect()
    try:
        total_row = conn.execute(
            "SELECT value FROM settings WHERE account_id = ? AND key = 'credits_total'", (account_id,)
        ).fetchone()
        credits_total = int(total_row["value"]) if total_row else 300
        rates = credit_rates(account_id, conn=conn)

        sub = conn.execute(
            "SELECT plan, billing_cycle, status, current_period_start, current_period_end "
            "FROM subscriptions WHERE account_id = ?",
            (account_id,),
        ).fetchone()
        if sub and sub["current_period_start"]:
            period_start = sub["current_period_start"]
        else:
            # No subscription yet (never checked out) — fall back to
            # calendar-month-to-date so a brand-new/legacy account still
            # gets a sane rolling window instead of lifetime-cumulative,
            # which used to make creditsRemaining hit 0 forever after one
            # month of any usage at all.
            period_start = conn.execute("SELECT date_trunc('month', now())::text AS s").fetchone()["s"]

        used, by_type, by_voice_tier = _credits_used_in_period(conn, account_id, rates, period_start)

        account_row = conn.execute("SELECT plan FROM accounts WHERE id = ?", (account_id,)).fetchone()
        plan = (sub["plan"] if sub else None) or (account_row["plan"] if account_row else "starter")
        plan_pricing = PLAN_PRICING.get(plan, PLAN_PRICING["starter"])
        overage_credits = max(0.0, round(used - credits_total, 1))
        per_credit_rate = plan_pricing["price_inr"] / plan_pricing["credits"]
        overage_rate_inr = round(per_credit_rate * OVERAGE_RATE_MULTIPLIER, 2)
        overage_amount_inr = round(overage_credits * overage_rate_inr, 2)

        phone_row = conn.execute(
            "SELECT COUNT(*) c, COALESCE(SUM(monthly_fee_inr), 0) fees FROM phone_numbers "
            "WHERE account_id = ? AND status = 'active'",
            (account_id,),
        ).fetchone()
        phone_number_fees_inr = float(phone_row["fees"] or 0)

        return {
            "creditsTotal": credits_total,
            "creditsUsed": used,
            "creditsRemaining": max(0, round(credits_total - used, 1)),
            "minutesUsed": round(sum(by_type.values()), 1),
            "minutesByType": by_type,
            "creditRates": rates,
            "minutesByVoiceTier": by_voice_tier,
            "voiceTierRates": _VOICE_TIER_MULTIPLIERS,
            "plan": plan,
            "planPriceInr": plan_pricing["price_inr"],
            "subscriptionStatus": sub["status"] if sub else "inactive",
            "billingCycle": sub["billing_cycle"] if sub else "monthly",
            "currentPeriodStart": sub["current_period_start"] if sub else None,
            "currentPeriodEnd": sub["current_period_end"] if sub else None,
            "overageCredits": overage_credits,
            "overageRateInr": overage_rate_inr,
            "overageAmountInr": overage_amount_inr,
            "phoneNumberCount": phone_row["c"],
            "phoneNumberFeesInr": phone_number_fees_inr,
            "estimatedNextInvoiceInr": round(overage_amount_inr + phone_number_fees_inr, 2),
        }
    finally:
        conn.close()


