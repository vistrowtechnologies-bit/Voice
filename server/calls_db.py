_CAMPAIGN_SEGMENTS = {"fresh", "followup", "failed_retry"}


def _contacts_for_segment(conn, account_id: int, segment: str, tag: str) -> list[dict]:
    """Contacts matching a campaign-picker segment (mirrors Ravan/Agni's
    Fresh Leads / Need Follow-up / Failed-Retry / All tabs) plus an optional
    tag filter, narrowed together. Segments:
      - "fresh": never been called (contacts.last_called_at IS NULL)
      - "followup": called at least once but not yet converted (status is
        still 'new' or 'qualified', not 'site_visit'/'customer')
      - "failed_retry": a previous campaign dial to this phone ended
        no_answer/failed — checked in Python against campaign_contacts'
        normalized phone_norm, since contacts.phone is stored in whatever
        raw format it was entered/imported in, not normalized.
      - "" / anything else / "all": no segment filter.
    Shared by create_campaign (the actual queue) and count_contacts_by_segment
    (the picker's live "N contacts match" preview), so what the operator
    previews is exactly what gets dialed."""
    q = "SELECT name, phone, company, custom_fields, last_called_at, status FROM contacts WHERE account_id = ? AND phone IS NOT NULL AND phone <> ''"
    params: list = [account_id]
    if tag:
        q += " AND tags LIKE ?"
        params.append(f"%{tag}%")
    rows = [dict(r) for r in conn.execute(q, tuple(params)).fetchall()]

    if segment == "fresh":
        rows = [r for r in rows if not r["last_called_at"]]
    elif segment == "followup":
        rows = [r for r in rows if r["last_called_at"] and r["status"] in ("new", "qualified")]
    elif segment == "failed_retry":
        failed_norms = {
            r["phone_norm"]
            for r in conn.execute(
                "SELECT DISTINCT phone_norm FROM campaign_contacts WHERE account_id = ? AND status IN ('no_answer', 'failed')",
                (account_id,),
            ).fetchall()
        }
        rows = [r for r in rows if _normalize_phone(r["phone"]) in failed_norms]
    return rows


def count_contacts_by_segment(account_id: int, segment: str, tag: str) -> int:
    conn = _connect()
    try:
        return len(_contacts_for_segment(conn, account_id, segment, tag))
    finally:
        conn.close()


def create_campaign(data: dict, account_id: int) -> int:
    """Create a campaign and load its call queue. The queue comes from either
    an explicit `contacts` list ([{name, phone}], e.g. a CSV upload) or a
    `contactTag` that pulls matching rows from the contacts table. Phones are
    deduped by normalized form so the same person isn't dialed twice. Returns
    the new campaign id. Starts in 'draft' — the dialer ignores it until the
    operator explicitly launches it (set_campaign_status running)."""
    conn = _connect()
    try:
        with conn:
            scheduled_date = data.get("scheduledDate") or None
            cur = conn.execute(
                f"""
                INSERT INTO campaigns
                    (account_id, name, agent_id, from_number, contact_tag, scheduled_date,
                     max_attempts, retry_minutes, concurrency, status)
                VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, {'?' if scheduled_date else "'draft'"})
                RETURNING id
                """,
                (
                    account_id,
                    data.get("name", "Untitled campaign"),
                    data.get("agentId"),
                    data.get("fromNumber", ""),
                    data.get("contactTag", ""),
                    scheduled_date,
                    max(1, int(data.get("maxAttempts", 1) or 1)),
                    max(1, int(data.get("retryMinutes", 60) or 60)),
                    max(1, int(data.get("concurrency", 1) or 1)),
                    *(["scheduled"] if scheduled_date else []),
                ),
            )
            campaign_id = cur.fetchone()["id"]

            rows: list[tuple[str, str, str, str]] = []  # (name, phone, company, custom_fields_json)
            explicit = data.get("contacts")
            if isinstance(explicit, list) and explicit:
                # Pasted/CSV-uploaded numbers carry no company/custom fields —
                # only a contacts-table row (the tag-based path below) has them.
                for c in explicit:
                    phone = str((c or {}).get("phone") or "").strip()
                    if phone:
                        rows.append((str((c or {}).get("name") or "").strip(), phone, "", "{}"))
            else:
                for r in _contacts_for_segment(conn, account_id, data.get("segment", ""), data.get("contactTag", "")):
                    rows.append((r["name"], r["phone"], r["company"] or "", r["custom_fields"] or "{}"))

            seen: set[str] = set()
            for name, phone, company, custom_fields in rows:
                norm = _normalize_phone(phone)
                if not norm or norm in seen:
                    continue
                seen.add(norm)
                conn.execute(
                    "INSERT INTO campaign_contacts (campaign_id, account_id, name, phone, phone_norm, company, custom_fields) "
                    "VALUES (?, ?, ?, ?, ?, ?, ?)",
                    (campaign_id, account_id, name, phone.strip(), norm, company, custom_fields),
                )
            return campaign_id
    finally:
        conn.close()


