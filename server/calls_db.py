def _hhmm_to_minutes(t: str) -> int:
    h, m = t.split(":")
    return int(h) * 60 + int(m)


def _slot_conflict(conn, account_id: int, appt_date: str, start_time: str, duration_minutes: int, exclude_id: int | None = None) -> bool:
    """Real SQL overlap check — only 'confirmed' rows on this date block a
    slot (cancelled/rescheduled/completed/no_show never do). Replaces
    Google's FreeBusy API entirely."""
    sql = (
        "SELECT start_time, duration_minutes FROM appointments "
        "WHERE account_id = ? AND appt_date = ? AND status = 'confirmed'"
    )
    params: list = [account_id, appt_date]
    if exclude_id:
        sql += " AND id != ?"
        params.append(exclude_id)
    rows = conn.execute(sql, tuple(params)).fetchall()
    new_start = _hhmm_to_minutes(start_time)
    new_end = new_start + duration_minutes
    for r in rows:
        s = _hhmm_to_minutes(r["start_time"])
        e = s + r["duration_minutes"]
        if new_start < e and new_end > s:
            return True
    return False


def check_availability(account_id: int, date: str, duration_minutes: int = 30) -> list[str]:
    """Open HH:MM slots for `date` given the account's availability config +
    existing confirmed bookings. [] if the day is a blackout date, weekday
    is closed, or every slot is booked/in the past (for today)."""
    cfg = get_availability_config(account_id)
    weekday = _DAY_ABBR[datetime.date.fromisoformat(date).weekday()]
    if date in (cfg.get("blackout_dates") or []):
        return []
    hours = (cfg.get("hours") or {}).get(weekday)
    if not hours:
        return []
    slot_minutes = int(cfg.get("slot_minutes", 30))
    open_m, close_m = _hhmm_to_minutes(hours["open"]), _hhmm_to_minutes(hours["close"])
    conn = _connect()
    try:
        now = datetime.datetime.now(ZoneInfo(cfg.get("timezone", "Asia/Kolkata")))
        is_today = date == now.date().isoformat()
        now_minutes = now.hour * 60 + now.minute
        slots: list[str] = []
        cursor = open_m
        while cursor + duration_minutes <= close_m:
            hhmm = f"{cursor // 60:02d}:{cursor % 60:02d}"
            if not (is_today and cursor <= now_minutes) and not _slot_conflict(conn, account_id, date, hhmm, duration_minutes):
                slots.append(hhmm)
            cursor += slot_minutes
        return slots
    finally:
        conn.close()


def book_appointment_native(
    account_id: int,
    agent_id: int | None,
    call_id: int | None,
    name: str,
    phone: str,
    date: str,
    time: str,
    duration_minutes: int,
    purpose: str = "",
    email: str = "",
    source: str = "agent",
) -> dict:
    """{"ok": True, "id": ...} or {"ok": False, "error": ...}. Takes a
    per-account-per-date advisory lock before the check-then-insert so two
    concurrent bookings for the same day can't both pass the conflict check
    before either commits (plain re-check alone doesn't prevent that under
    READ COMMITTED)."""
    conn = _connect()
    try:
        with conn:
            conn.execute("SELECT pg_advisory_xact_lock(hashtext(?))", (f"appt:{account_id}:{date}",))
            if _slot_conflict(conn, account_id, date, time, duration_minutes):
                return {"ok": False, "error": "slot no longer available"}
            cur = conn.execute(
                "INSERT INTO appointments (account_id, agent_id, call_id, contact_name, contact_phone, "
                "contact_email, purpose, appt_date, start_time, duration_minutes, status, source) "
                "VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, 'confirmed', ?) RETURNING id",
                (account_id, agent_id, call_id, name, phone, email, purpose, date, time, duration_minutes, source),
            )
            return {"ok": True, "id": cur.lastrowid}
    finally:
        conn.close()


