# Column-mapping targets that write to a built-in contacts column rather
# than becoming a custom_fields entry — mirrors Facebook Custom Audience's
# upload-and-map flow instead of requiring exact header names like the old
# fixed-column import did.
_BUILTIN_MAPPING_TARGETS = {"first_name", "last_name", "name", "phone", "email", "company", "tags"}


def import_contacts_mapped(text: str, mapping: dict, account_id: int) -> int:
    """Import a CSV using an explicit header -> target mapping. `mapping` is
    {csv_header: target}, where target is one of _BUILTIN_MAPPING_TARGETS,
    "" (skip this column), or any other string — that string becomes the
    contact's custom_fields key, so a column mapped to "appointment_date"
    is later available to a campaign call as {{custom.appointment_date}}
    (see agent/main.py's template substitution)."""
    reader = csv.DictReader(io.StringIO(text))
    count = 0
    for row in reader:
        first_name = last_name = name = phone = email = company = tags = ""
        custom: dict = {}
        for header, value in row.items():
            target = mapping.get(header, "")
            value = (value or "").strip()
            if not target or not value:
                continue
            if target == "first_name":
                first_name = value
            elif target == "last_name":
                last_name = value
            elif target == "name":
                name = value
            elif target == "phone":
                phone = value
            elif target == "email":
                email = value
            elif target == "company":
                company = value
            elif target == "tags":
                tags = value
            else:
                custom[target] = value
        if not phone:
            continue
        create_contact(
            {
                "name": name or " ".join(p for p in (first_name, last_name) if p) or "Unknown",
                "phone": phone,
                "email": email,
                "company": company,
                "tags": tags,
                "customFields": custom,
                "source": "import",
            },
            account_id,
        )
        count += 1
    return count


def contact_detail(contact_id: int, account_id: int) -> dict | None:
    """Everything the Contacts detail page's Activity/Calls/Campaigns/Notes
    tabs need in one call. Call-outcome stats prefer campaign_contacts'
    own status/outcome (joined by call_id) where a call was placed by a
    campaign, since that's a real no_answer/failed/blocked classification —
    duration_seconds alone (the only signal on non-campaign calls: widget,
    inbound, browser test) can't distinguish "declined immediately" from
    "rang out unanswered", so those fall back to a coarser completed/
    no-answer split by whether any talk time was recorded."""
    conn = _connect()
    try:
        contact = conn.execute(
            "SELECT * FROM contacts WHERE id = ? AND account_id = ?", (contact_id, account_id)
        ).fetchone()
        if contact is None:
            return None
        phone = contact["phone"] or ""

        calls = (
            conn.execute(
                "SELECT id, started_at, duration_seconds, call_type FROM calls "
                "WHERE account_id = ? AND lead_phone = ? ORDER BY started_at DESC",
                (account_id, phone),
            ).fetchall()
            if phone
            else []
        )
        # call_id -> campaign_contacts.status, for the calls that were placed
        # by a campaign dial (NULL/missing for widget/inbound/browser calls).
        campaign_outcome_by_call_id: dict[int, str] = {}
        if calls:
            call_ids = [c["id"] for c in calls]
            placeholders = ",".join("?" * len(call_ids))
            for r in conn.execute(
                f"SELECT call_id, status FROM campaign_contacts WHERE call_id IN ({placeholders})",
                tuple(call_ids),
            ).fetchall():
                campaign_outcome_by_call_id[r["call_id"]] = r["status"]

        total_calls = len(calls)
        completed = no_answer = failed = 0
        total_seconds = 0.0
        for c in calls:
            duration = c["duration_seconds"] or 0
            total_seconds += duration
            outcome = campaign_outcome_by_call_id.get(c["id"])
            if outcome == "failed":
                failed += 1
            elif outcome == "no_answer":
                no_answer += 1
            elif duration > 0:
                completed += 1
            else:
                no_answer += 1

        campaign_rows = (
            conn.execute(
                "SELECT cc.status, cc.outcome, cc.attempts, c.id AS campaign_id, c.name AS campaign_name, "
                "c.status AS campaign_status FROM campaign_contacts cc "
                "JOIN campaigns c ON c.id = cc.campaign_id "
                "WHERE cc.account_id = ? AND cc.phone_norm = ? ORDER BY c.id DESC",
                (account_id, _normalize_phone(phone)),
            ).fetchall()
            if phone
            else []
        )

        notes = conn.execute(
            "SELECT id, body, created_by, created_at FROM contact_notes "
            "WHERE contact_id = ? AND account_id = ? ORDER BY created_at DESC",
            (contact_id, account_id),
        ).fetchall()

        return {
            "id": contact["id"],
            "name": contact["name"],
            "phone": phone,
            "email": contact["email"] or "",
            "company": contact["company"] or "",
            "customFields": _safe_json_loads(contact["custom_fields"]),
            "status": contact["status"],
            "tags": [t for t in (contact["tags"] or "").split(",") if t],
            "source": contact["source"],
            "createdAt": contact["created_at"],
            "updatedAt": contact["updated_at"],
            "lastCalledAt": contact["last_called_at"],
            "callStats": {
                "total": total_calls,
                "completed": completed,
                "noAnswer": no_answer,
                "failed": failed,
                "avgDurationSeconds": round(total_seconds / completed) if completed else 0,
                "totalDurationSeconds": round(total_seconds),
            },
            "calls": [
                {"id": c["id"], "startedAt": c["started_at"], "durationSeconds": c["duration_seconds"] or 0, "callType": c["call_type"]}
                for c in calls
            ],
            "campaigns": [
                {
                    "campaignId": r["campaign_id"],
                    "campaignName": r["campaign_name"],
                    "campaignStatus": r["campaign_status"],
                    "contactStatus": r["status"],
                    "outcome": r["outcome"],
                    "attempts": r["attempts"],
                }
                for r in campaign_rows
            ],
            "notes": [
                {"id": n["id"], "body": n["body"], "createdBy": n["created_by"], "createdAt": n["created_at"]}
                for n in notes
            ],
        }
    finally:
        conn.close()


