def create_privacy_request(user_id: int, account_id: int, request_type: str, status: str = "pending") -> dict:
    if request_type not in ("export", "deletion"):
        raise ValueError("invalid privacy request type")
    conn = _connect()
    try:
        with conn:
            # Repeated clicks should not flood the admin queue.
            existing = conn.execute(
                "SELECT * FROM privacy_requests WHERE user_id = ? AND request_type = ? "
                "AND status IN ('pending','in_progress') ORDER BY id DESC LIMIT 1",
                (user_id, request_type),
            ).fetchone()
            if existing is not None:
                return dict(existing)
            cur = conn.execute(
                "INSERT INTO privacy_requests (user_id, account_id, request_type, status) VALUES (?, ?, ?, ?) RETURNING id",
                (user_id, account_id, request_type, status),
            )
        row = conn.execute("SELECT * FROM privacy_requests WHERE id = ?", (cur.lastrowid,)).fetchone()
        return dict(row)
    finally:
        conn.close()


