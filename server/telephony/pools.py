"""Telephony capacity: provider account (physical pool) → trunk (per-customer
allocation) → number → lines. Plan: docs/META-LEAD-ADS-PLAN-2026-10-22.md,
section 2a.

A *line* is one concurrent outbound call. Capacity is physical only at the
provider-account level (EnableX confirmed 18 Sep 2026 that channels and CPS
are per account, not per number or trunk, and the same pool serves inbound),
so a customer's trunk never buys capacity from the carrier: it is an
allocation out of a pool, and the sum of allocations can never exceed the
pool minus the inbound reserve. That rule is enforced twice: in Python under
a row lock on the pool, and by a database trigger, so two sales racing each
other cannot oversell a line we have not bought.

Today's state migrates unchanged: one EnableX pool with OUTBOUND_CHANNEL_LIMIT
(default 2) outbound lines plus 1 reserved for inbound, one platform-shared
trunk holding every existing number. The dialer keeps dialling exactly as it
does now until a customer is allocated lines of their own.

Nothing here talks to a carrier; providers.py describes how each one is
provisioned and billed, without network calls.
"""

from __future__ import annotations

import logging
import os

import calls_db
import integration_crypto

logger = logging.getLogger("telephony")

DEFAULT_OUTBOUND_LINES = 2       # mirrors campaign_dialer._OUTBOUND_CHANNELS' default
DEFAULT_INBOUND_RESERVE = 1      # the pool is 1 inbound + 2 outbound today
PLATFORM_PROVIDER = "enablex"
_SECRET_OPT_IN_ENVS = ("TELEPHONY_ALLOW_PLAINTEXT_SECRETS", "META_ALLOW_PLAINTEXT_TOKENS")


class OverSell(Exception):
    """Allocating these lines would exceed what the pool has bought."""


class SecretStorageUnavailable(Exception):
    """Refusing to store SIP credentials in plaintext."""


# ----------------------------------------------------------------- schema

_SCHEMA = f"""
CREATE TABLE IF NOT EXISTS telephony_providers (
    key TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    status TEXT DEFAULT 'coming_soon',
    provisioning TEXT DEFAULT 'manual',
    capacity_unit TEXT DEFAULT 'per_line',
    over_capacity TEXT DEFAULT 'sip_error',
    cost_per_line_month REAL DEFAULT 0,
    cost_per_minute_in REAL DEFAULT 0,
    cost_per_minute_out REAL DEFAULT 0,
    cost_per_number_month REAL DEFAULT 0
);

-- The PHYSICAL capacity: one row per carrier account we (owner_account_id
-- NULL) or a customer hold.
CREATE TABLE IF NOT EXISTS provider_pools (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_key TEXT NOT NULL,
    owner_account_id INTEGER,
    credentials TEXT DEFAULT '',
    lines_bought INTEGER NOT NULL DEFAULT 0,
    cps_bought INTEGER NOT NULL DEFAULT 0,
    inbound_reserved_lines INTEGER NOT NULL DEFAULT 0,
    notes TEXT DEFAULT '',
    created_at TEXT DEFAULT {calls_db._NOW}
);

-- A customer's allocation out of a pool. account_id NULL = platform shared.
CREATE TABLE IF NOT EXISTS trunks (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id INTEGER,
    pool_id INTEGER NOT NULL REFERENCES provider_pools (id),
    sip_address TEXT DEFAULT '',
    lines INTEGER NOT NULL DEFAULT 0,
    cps_share INTEGER NOT NULL DEFAULT 0,
    lk_outbound_trunk_id TEXT DEFAULT '',
    status TEXT DEFAULT 'active',
    notes TEXT DEFAULT '',
    provisioned_at TEXT,
    created_at TEXT DEFAULT {calls_db._NOW}
);
CREATE INDEX IF NOT EXISTS idx_trunks_pool ON trunks (pool_id);
CREATE INDEX IF NOT EXISTS idx_trunks_account ON trunks (account_id);

-- Which trunk a number dials out on; NULL means the platform-shared trunk.
ALTER TABLE phone_numbers ADD COLUMN IF NOT EXISTS trunk_id INTEGER;

-- Database-side guard: the pool can never be oversold, whatever path wrote
-- the trunk row. The pool row is locked first so concurrent writers queue
-- and the second one sees the first one's lines.
-- (Percent signs are doubled: dbconn.Conn.execute always hands psycopg a
-- params tuple, so a literal percent sign must be written twice, as
-- everywhere else in this codebase.)
CREATE OR REPLACE FUNCTION trunks_pool_cap_check() RETURNS trigger AS $$
DECLARE
    pool provider_pools%%ROWTYPE;
    allocated INTEGER;
BEGIN
    SELECT * INTO pool FROM provider_pools WHERE id = NEW.pool_id FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'telephony: pool %% does not exist', NEW.pool_id;
    END IF;
    SELECT COALESCE(SUM(lines), 0) INTO allocated FROM trunks
     WHERE pool_id = NEW.pool_id AND status = 'active' AND id <> NEW.id;
    IF NEW.status = 'active' AND allocated + NEW.lines > pool.lines_bought - pool.inbound_reserved_lines THEN
        RAISE EXCEPTION 'telephony_oversell: pool %% has %% line(s) for allocation, %% already allocated, %% requested',
            NEW.pool_id, pool.lines_bought - pool.inbound_reserved_lines, allocated, NEW.lines;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE TRIGGER trunks_pool_cap_check_trg
    BEFORE INSERT OR UPDATE OF lines, status, pool_id ON trunks
    FOR EACH ROW EXECUTE FUNCTION trunks_pool_cap_check();

-- Shrinking a pool below what is already allocated is refused too.
CREATE OR REPLACE FUNCTION pool_shrink_check() RETURNS trigger AS $$
DECLARE
    allocated INTEGER;
BEGIN
    SELECT COALESCE(SUM(lines), 0) INTO allocated FROM trunks WHERE pool_id = NEW.id AND status = 'active';
    IF allocated > NEW.lines_bought - NEW.inbound_reserved_lines THEN
        RAISE EXCEPTION 'telephony_oversell: pool %% already has %% line(s) allocated; cannot shrink to %%',
            NEW.id, allocated, NEW.lines_bought - NEW.inbound_reserved_lines;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE TRIGGER pool_shrink_check_trg
    BEFORE UPDATE OF lines_bought, inbound_reserved_lines ON provider_pools
    FOR EACH ROW EXECUTE FUNCTION pool_shrink_check();
"""

